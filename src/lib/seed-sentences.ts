import type { Exercise, Level, VocabItem } from "./types";

// Built-in sentence bank: works without an API key and costs nothing to grade
// when the answer matches one of the accepted translations.

function ex(
  id: string,
  level: Level,
  topicId: string,
  tr: string,
  de: string[],
  vocab: [string, string][],
  hint: string,
): Exercise {
  return {
    id: `seed-${id}`,
    level,
    topicId,
    tr,
    de,
    vocab: vocab.map(([d, t]): VocabItem => ({ de: d, tr: t })),
    hint,
    source: "seed",
  };
}

